"""Правила согласия на обработку персональных данных (152-ФЗ).

- При первом обращении клиент получает короткий текст со ссылкой на политику салона.
- Согласие — явное: отдельным сообщением «Согласен» / «Согласна» / «Даю согласие», а не
  «продолжая переписку, вы соглашаетесь». В журнал пишется версия текста согласия.
- Без согласия агент отвечает только на общие вопросы (услуги, цены, адрес, свободное время):
  телефон и e-mail из сообщения заменяются заглушкой до сохранения и до отправки в LLM,
  записать клиента нельзя.
- Отзыв согласия — командой /forget или просьбой в чате («отзываю согласие», «удалите мои данные»):
  переписка и журнал вызовов инструментов удаляются, карточка клиента обезличивается.

Модуль без ввода-вывода: только правила, их проверяют unit-тесты.
"""

import re
from enum import StrEnum

# Версия текста согласия и политики: меняется вместе с текстом, старые согласия остаются со своей версией
CONSENT_VERSION = "2026-11-17"

_PHONE = re.compile(r"(?<!\w)\+?\d[\d\s()\-]{8,}\d(?!\w)")
_EMAIL = re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+")
_SPACES = re.compile(r"[\s!.,;:)(«»\"']+")
_GRANT = {
    "согласен",
    "согласна",
    "я согласен",
    "я согласна",
    "да согласен",
    "да согласна",
    "даю согласие",
    "да даю согласие",
    "согласен на обработку",
    "согласна на обработку",
    "согласен на обработку данных",
    "согласна на обработку данных",
    "/agree",
}
_WITHDRAW = re.compile(
    r"(^/forget\b)|(отзыва\w*|отозва\w*)[\s,]+(\w+[\s,]+)?согласи"
    r"|удал\w*[\s,]+(\w+[\s,]+){0,2}(мои|мою|мой)\s+(\w+\s+)?(данные|переписк\w*|номер|телефон)",
    re.IGNORECASE,
)


class ConsentState(StrEnum):
    NONE = "none"  # ещё не давал
    GRANTED = "granted"
    WITHDRAWN = "withdrawn"


class ConsentIntent(StrEnum):
    NONE = "none"
    GRANT = "grant"
    WITHDRAW = "withdraw"


def detect_intent(text: str) -> ConsentIntent:
    """Согласие — только целым коротким сообщением: «согласна на 15:00» согласием не считается."""
    if _WITHDRAW.search(text.strip()):
        return ConsentIntent.WITHDRAW
    normalized = _SPACES.sub(" ", text.lower().replace("ё", "е")).strip()
    return ConsentIntent.GRANT if normalized in _GRANT else ConsentIntent.NONE


def allows_personal_data(state: ConsentState) -> bool:
    return state is ConsentState.GRANTED


def _phone(match: re.Match[str]) -> str:
    digits = sum(char.isdigit() for char in match.group())
    return "[телефон скрыт]" if 10 <= digits <= 15 else match.group()  # «1500 2000» — не телефон


def strip_personal_data(text: str) -> str:
    """Телефон и e-mail → заглушка: без согласия их нельзя ни хранить, ни передавать в LLM."""
    return _EMAIL.sub("[e-mail скрыт]", _PHONE.sub(_phone, text))


def consent_request(policy_url: str) -> str:
    return (
        "Чтобы записать вас, нужно согласие на обработку персональных данных (имя и телефон) "
        f"по политике салона: {policy_url}\n"
        "Если согласны, ответьте одним словом «Согласен» или «Согласна». "
        "На общие вопросы отвечу и без этого. Отозвать согласие можно в любой момент командой /forget."
    )


